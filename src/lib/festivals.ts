/**
 * Returns all festivals falling on a given YYYY-MM-DD date
 */
export function getFestivalsForDate(dateStr: string): CalendarFestival[] {
  const year = parseInt(dateStr.slice(0, 4), 10);
  return COMPREHENSIVE_FESTIVALS.filter((f) => f.dates[year] === dateStr);
}

/**
 * Returns all festivals for a specific year and month (0-indexed month: 0=Jan, 10=Nov, 11=Dec)
 */
export function getFestivalsForMonth(year: number, monthIndex: number): CalendarFestival[] {
  const monthStr = String(monthIndex + 1).padStart(2, "0");
  const prefix = `${year}-${monthStr}-`;
  return COMPREHENSIVE_FESTIVALS.filter((f) => {
    const d = f.dates[year];
    return d && d.startsWith(prefix);
  }).sort((a, b) => a.dates[year].localeCompare(b.dates[year]));
}

